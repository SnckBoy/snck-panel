const isSafeRelativeMarketplacePath = (value: unknown) => {
  const normalized = String(value || "").replace(/\\/g, "/");
  return Boolean(normalized) && !normalized.startsWith("/") && !normalized.startsWith("\\") && !/^[A-Za-z]:/.test(normalized) && !normalized.split("/").some((part) => part === ".." || part === "");
};
const verifyMarketplaceHash = (bytes: Buffer, hashes: any) => {
  if (!hashes || typeof hashes !== "object") return;
  if (typeof hashes.sha512 === "string" && crypto.createHash("sha512").update(bytes).digest("hex") !== hashes.sha512.toLowerCase()) throw new Error("Modrinth file SHA-512 verification failed");
  if (typeof hashes.sha1 === "string" && crypto.createHash("sha1").update(bytes).digest("hex") !== hashes.sha1.toLowerCase()) throw new Error("Modrinth file SHA-1 verification failed");
};
const buildMrpackInstallTree = async (archiveRoot: string, outputRoot: string) => {
  const manifestPath = path.join(archiveRoot, "modrinth.index.json");
  if (!(await fs.pathExists(manifestPath))) throw new Error("The .mrpack archive is missing modrinth.index.json");
  const manifest = await fs.readJSON(manifestPath);
  if (manifest?.formatVersion !== 1 || manifest?.game !== "minecraft" || !Array.isArray(manifest.files)) throw new Error("Unsupported or invalid Modrinth pack manifest");
  await fs.ensureDir(outputRoot);
  let totalBytes = 0;
  for (const entry of manifest.files) {
    const relativePath = String(entry?.path || "").replace(/\\/g, "/");
    if (!isSafeRelativeMarketplacePath(relativePath)) throw new Error("Modrinth manifest contains an unsafe file path");
    if (entry?.env?.server === "unsupported") continue;
    const downloads = Array.isArray(entry?.downloads) ? entry.downloads.filter((value: unknown) => typeof value === "string") : [];
    const url = downloads[0] || "";
    if (!url) throw new Error(`Modrinth manifest has no download URL for ${relativePath}`);
    const bytes = await downloadMarketplaceBinary(url);
    totalBytes += bytes.length;
    if (totalBytes > 512 * 1024 * 1024) throw new Error("Modrinth pack dependencies exceed the 512 MB safety limit");
    verifyMarketplaceHash(bytes, entry.hashes);
    const target = path.join(outputRoot, relativePath);
    await fs.ensureDir(path.dirname(target));
    await fs.writeFile(target, bytes);
  }
  for (const override of ["overrides", "server-overrides"]) {
    const overridePath = path.join(archiveRoot, override);
    if (await fs.pathExists(overridePath)) await copyDirectorySafely(overridePath, outputRoot);
  }
  const dependencies = manifest.dependencies && typeof manifest.dependencies === "object" ? manifest.dependencies : {};
  const runtimeType = dependencies["fabric-loader"] ? "FABRIC" : dependencies.forge ? "FORGE" : dependencies.neoforge ? "NEOFORGE" : dependencies["quilt-loader"] ? "QUILT" : null;
  return { name: String(manifest.name || "Modrinth pack"), files: totalBytes, runtimeType, minecraftVersion: typeof dependencies.minecraft === "string" ? dependencies.minecraft : null };
};
const persistDetectedMrpackRuntime = async (serverId: string, detected: { runtimeType: string | null; minecraftVersion: string | null }) => {
  if (!detected.runtimeType && !detected.minecraftVersion) return;
  const servers = await readJSON("servers.json") || [];
  const server = servers.find((candidate: any) => candidate.id === serverId);
  if (!server) return;
  if (detected.runtimeType) server.type = detected.runtimeType;
  if (detected.minecraftVersion) server.version = detected.minecraftVersion;
  server.runtimeDetectedAt = new Date().toISOString();
  await writeJSON("servers.json", servers);
};
const collectArchiveFiles = async (root: string, current = ""): Promise<Array<{ path: string; content: string }>> => {
  const directory = path.join(root, current);
  const entries = await fs.readdir(directory, { withFileTypes: true });
  const files: Array<{ path: string; content: string }> = [];
  for (const entry of entries) {
    const rel = path.posix.join(current.split(path.sep).join("/"), entry.name);
    const absolute = path.join(directory, entry.name);
    if (entry.isDirectory()) files.push(...await collectArchiveFiles(root, path.join(current, entry.name)));
    else if (entry.isFile() && entry.name !== "modrinth.index.json") {
      const bytes = await fs.readFile(absolute);
      files.push({ path: rel, content: bytes.toString("base64") });
    }
  }
  return files;
};

export const installPlugin = async (req: Request, res: Response) => {
  const { id } = req.params;
  const { source, pluginId, pluginName, gameVersion, loader } = req.body;
  const server = (req as any).server || {};
  const effectiveGameVersion = typeof gameVersion === "string" && gameVersion.trim() ? gameVersion.trim() : String(server.version || "").trim();
  const effectiveLoader = typeof loader === "string" && loader.trim() ? loader.trim() : String(server.type || "").trim().toLowerCase();
  
  // Allow direct downloadUrl fallback for backward compatibility
  if (req.body.downloadUrl) {
    try {
      const filename = marketplaceFilename(req.body.filename, "plugin.jar");
      const bytes = await downloadMarketplaceBinary(String(req.body.downloadUrl));
      await writeMarketplaceBinary(req, id, `plugins/${filename}`, bytes);
      return res.json({ success: true, message: "Plugin installed successfully" });
    } catch (e: any) {
      return res.status(502).json({ error: e?.message || "Failed to install plugin" });
    }
  }

  if (!source || !pluginId || !pluginName) {
    return res.status(400).json({ error: "Missing source, pluginId, or pluginName" });
  }

  try {
    const serverDir = path.join(process.cwd(), ".data", "servers", id);
    const pluginsDir = path.join(serverDir, "plugins");
    await fs.ensureDir(pluginsDir);
    
    let downloadUrl = null;
    let filename = `${pluginName.replace(/[^a-zA-Z0-9]/g, '_')}.jar`;
    const axios = (await import("axios")).default;

    const resolveGithubRelease = async (extUrl: string) => {
      if (extUrl.includes('github.com') && extUrl.includes('/releases/')) {
        let apiUrl = null;
        const match = extUrl.match(/github\.com\/([^\/]+)\/([^\/]+)\/releases\/tag\/([^\/]+)/);
        if (match) {
          apiUrl = `https://api.github.com/repos/${match[1]}/${match[2]}/releases/tags/${match[3]}`;
        } else {
          const matchLatest = extUrl.match(/github\.com\/([^\/]+)\/([^\/]+)\/releases\/latest/);
          if (matchLatest) {
            apiUrl = `https://api.github.com/repos/${matchLatest[1]}/${matchLatest[2]}/releases/latest`;
          }
        }
        if (apiUrl) {
          try {
            const ghRes = await axios.get(apiUrl);
            if (ghRes.data && ghRes.data.assets) {
              const jarAsset = ghRes.data.assets.find((a: any) => a.name.endsWith('.jar'));
              if (jarAsset) {
                return { url: jarAsset.browser_download_url, filename: jarAsset.name };
              }
            }
          } catch(e) {
            console.error('GitHub API error:', e);
          }
        }
      }
      return null;
    };

    if (source === 'modrinth') {
      const resolved = await resolveModrinthVersion(pluginId, effectiveGameVersion, effectiveLoader);
      downloadUrl = resolved.file.url;
      filename = resolved.file.filename || filename;
    } else if (source === 'spiget' || source === 'spigot') {
       const apiRes = await axios.get(`https://api.spiget.org/v2/resources/${pluginId}`);
       if (apiRes.data && apiRes.data.file) {
         if (apiRes.data.file.type === 'external' && apiRes.data.file.externalUrl) {
           const extUrl = apiRes.data.file.externalUrl;
           const ghAsset = await resolveGithubRelease(extUrl);
           if (ghAsset) {
             downloadUrl = ghAsset.url;
             filename = ghAsset.filename;
           }
           if (!downloadUrl) {
             return res.status(400).json({ error: "This plugin must be downloaded externally from: " + extUrl });
           }
         } else {
           downloadUrl = `https://api.spiget.org/v2/resources/${pluginId}/download`;
         }
       } else {
         downloadUrl = `https://api.spiget.org/v2/resources/${pluginId}/download`;
       }
    } else if (source === 'hangar') {
       const [owner, slug] = pluginId.split('/');
       const verRes = await axios.get(`https://hangar.papermc.io/api/v1/projects/${owner}/${slug}/versions`);
       if (verRes.data && verRes.data.result && verRes.data.result.length > 0) {
         const version = verRes.data.result[0];
         const download = version.downloads.PAPER || Object.values(version.downloads)[0];
         if (download && (download as any).downloadUrl) {
            downloadUrl = (download as any).downloadUrl;
            if ((download as any).fileInfo && (download as any).fileInfo.name) {
                filename = (download as any).fileInfo.name;
            }
         } else if (download && (download as any).externalUrl) {
            const extUrl = (download as any).externalUrl;
            const ghAsset = await resolveGithubRelease(extUrl);
            if (ghAsset) {
              downloadUrl = ghAsset.url;
              filename = ghAsset.filename;
            } else {
              return res.status(400).json({ error: "This plugin must be downloaded externally from: " + extUrl });
            }
         }
       }
    }

    if (!downloadUrl) {
      return res.status(404).json({ error: "Could not find a valid download URL for this plugin." });
    }

    const bytes = await downloadMarketplaceBinary(String(downloadUrl));
    await writeMarketplaceBinary(req, id, `plugins/${marketplaceFilename(filename, "plugin.jar")}`, bytes);

    res.json({ success: true, message: "Plugin installed successfully" });
  } catch (error: any) {
    console.error("Plugin installation failed:", error.message);
    res.status(500).json({ error: "Plugin installation failed: " + error.message });
  }
};

