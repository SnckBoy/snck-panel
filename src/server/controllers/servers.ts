const nodeOperationError = (error: any, fallback: string) => {
  const dockerUnavailable = error?.dockerUnavailable === true || error?.responseData?.dockerUnavailable === true;
  const nodeUnavailable = error?.nodeUnavailable === true;
  const timeout = error?.timeout === true;
  const authFailed = error?.authFailed === true || Number(error?.statusCode) === 401;
  const responseInvalid = error?.nodeResponseInvalid === true;
  const message = String(error?.message || error?.responseData?.error || fallback);
  const statusCode = Number(error?.statusCode || (dockerUnavailable || nodeUnavailable ? 503 : 500));
  const safeStatus = authFailed ? 502 : (responseInvalid ? 502 : ((dockerUnavailable || nodeUnavailable || timeout) ? 503 : (statusCode >= 400 && statusCode < 600 ? statusCode : 500)));
  const body: any = dockerUnavailable ? { error: message, dockerUnavailable: true } : { error: message };
  if (authFailed) {
    body.nodeAuthenticationFailed = true;
    body.hint = "The daemon rejected the node credential. Reconnect or rotate the node credential, then reinstall the node configuration if necessary.";
  } else if (responseInvalid) {
    body.nodeResponseInvalid = true;
    body.hint = "The endpoint responded, but it is not a ShiroNex daemon response. Check the FQDN route, Cloudflare Access policy, tunnel ingress, and daemon version.";
  } else if (timeout) {
    body.nodeUnavailable = nodeUnavailable;
    body.timeout = true;
    body.hint = "The node or Cloudflare proxy did not complete the request in time. Confirm the daemon is running, then check the FQDN, Cloudflare Tunnel/Zero Trust ingress, daemon port, firewall, and image-pull connectivity. Initial Minecraft image pulls may take several minutes.";
  } else if (nodeUnavailable) {
    body.nodeUnavailable = true;
    body.timeout = false;
    body.hint = "Verify the node FQDN, DNS, Cloudflare Tunnel or Zero Trust ingress, TLS mode, daemon port, and firewall before retrying.";
  }
  return { statusCode: safeStatus, body };
};

export const getServers = async (req: Request, res: Response) => {
  const user = (req as any).user;
  const servers = await readJSON("servers.json") || [];
  
  // Filter for normal users
  const userServers = user.role === "admin" || user.role === "owner" ? servers : servers.filter((s: any) => s.owner === user.id);

  // Update statuses
  const [usersData, nodesData] = await Promise.all([readJSON("users.json"), readJSON("nodes.json")]);
  const users = usersData || [];
  const nodes = nodesData || [];
  const updatedServers = await Promise.all(userServers.map(async (server: any) => {
    const next = { ...server };
    if (server.containerId) {
      try {
        const status = await getContainerStatus(server.containerId, server.nodeId);
        next.status = status?.State?.Running ? "online" : "offline";
      } catch (error: any) {
        // A single unreachable node must not blank the whole fleet view.
        next.status = "offline";
        next.nodeUnavailable = error?.nodeUnavailable === true;
        next.nodeError = error?.message || "Node status is temporarily unavailable.";
      }
    }
    const ownerRecord = users.find((candidate: any) => candidate.id === server.owner);
    const nodeRecord = nodes.find((candidate: any) => candidate.id === (server.nodeId || "local"));
    return {
      ...next,
      nodeId: server.nodeId || "local",
      nodeName: nodeRecord?.name || (server.nodeId === "local" ? "Local Node" : "Unknown node"),
      nodeStatus: nodeStatusForServer(nodeRecord),
      ownerUsername: ownerRecord?.username || server.owner || "Unassigned",
      address: `${server.ipAlias || nodeRecord?.publicIp || nodeRecord?.hostname || "127.0.0.1"}:${server.port || "—"}`,
      lastActivity: server.updatedAt || server.lastActivity || server.createdAt || null,
      playersOnline: server.playersOnline ?? null,
      playersMax: server.playersMax ?? null,
    };
  }));

  res.json(updatedServers);
};

